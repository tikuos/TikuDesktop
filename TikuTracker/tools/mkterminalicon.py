"""Emit the Terminal's HVIF icon on the toolkit's 64-unit canvas.

A dark screen in a slate frame with a green prompt and a block cursor,
readable at 14 px.
SPDX-License-Identifier: Apache-2.0
"""
from mkhvif import icon, path_polygon, shape, style_solid, rect


layers = []


def add(color, points):
    layers.append((style_solid(color), path_polygon(points)))


# The frame: a dark outline, the slate bezel and a lit top-left edge.
add((28, 31, 38, 255), [(8, 6), (56, 6), (60, 10), (60, 50), (56, 54),
                       (8, 54), (4, 50), (4, 10)])
add((104, 112, 124, 255), [(9, 9), (55, 9), (57, 11), (57, 49), (55, 51),
                          (9, 51), (7, 49), (7, 11)])
add((70, 76, 88, 255), [(11, 12), (55, 12), (57, 14), (57, 49), (55, 51),
                       (11, 51), (9, 49), (9, 14)])
# The screen, near black with a faint green cast.
add((14, 20, 18, 255), rect(11, 13, 53, 47))
# The prompt: a chevron and a block cursor in phosphor green.
add((92, 230, 120, 255), [(16, 20), (28, 30), (16, 40), (16, 34), (21, 30),
                         (16, 26)])
add((92, 230, 120, 255), rect(31, 33, 43, 40))
# The stand.
add((28, 31, 38, 255), rect(24, 54, 40, 60))
add((92, 100, 112, 255), rect(26, 55, 38, 58))

blob = icon([s for s, _ in layers], [p for _, p in layers],
            [shape(i, i) for i in range(len(layers))])
print("/* Generated by TikuTracker/tools/mkterminalicon.py.\n"
      " * Authored TikuOS vector artwork; SPDX-License-Identifier: Apache-2.0 */")
print("static const uint8_t tiku_icon_terminal[] = {")
for at in range(0, len(blob), 12):
    print("    " + ", ".join(f"0x{b:02x}" for b in blob[at:at+12]) + ",")
print("};")
