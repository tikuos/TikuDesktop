"""Emit TikuReader's open-book HVIF artwork as a C array.

Blue covers, ivory pages, and a gold bookmark on the toolkit's 64-unit canvas.
SPDX-License-Identifier: Apache-2.0
"""
from mkhvif import icon, path_polygon, shape, style_solid


layers = []


def add(color, points):
    layers.append((style_solid(color), path_polygon(points)))


# Shadow and the dark outline of both covers.
add((30, 39, 50, 55), [(5, 52), (32, 63), (63, 53), (36, 45)])
add((33, 48, 69, 255), [(3, 15), (25, 7), (32, 12), (52, 7),
                       (61, 14), (61, 51), (35, 60), (29, 60), (3, 51)])
add((48, 105, 163, 255), [(5, 17), (25, 10), (31, 15), (31, 57), (5, 49)])
add((74, 141, 198, 255), [(33, 15), (53, 10), (59, 15), (59, 49), (33, 57)])
# Visible page edges and the two gently angled page faces.
add((190, 178, 148, 255), [(8, 17), (29, 17), (32, 18), (56, 17),
                         (56, 47), (33, 55), (28, 53), (8, 47)])
add((245, 236, 211, 255), [(7, 14), (24, 9), (30, 14), (30, 51),
                         (24, 47), (7, 43)])
add((255, 252, 235, 255), [(33, 14), (51, 9), (57, 14), (57, 43),
                         (35, 51), (33, 51)])
add((154, 153, 138, 255), [(30, 14), (32, 16), (33, 51), (30, 52)])
add((255, 253, 239, 255), [(8, 14), (24, 10), (28, 13), (24, 12), (8, 16)])
# Sparse text strokes stay legible without becoming a miniature text dump.
for y in (21, 28, 35):
    add((150, 153, 146, 255), [(11, y), (24, y-3), (26, y-2),
                             (26, y), (24, y-1), (11, y+2)])
for y in (34, 40):
    add((160, 163, 150, 255), [(37, y), (52, y-5), (52, y-3), (37, y+2)])
# A bookmark descending from the top of the right-hand page.
add((129, 85, 24, 255), [(43, 12), (50, 10), (50, 33), (46, 30), (43, 35)])
add((243, 184, 57, 255), [(44, 13), (49, 12), (49, 30), (46, 28), (44, 31)])
add((255, 222, 119, 255), [(44, 13), (46, 12), (46, 27), (44, 30)])

blob = icon([s for s, _ in layers], [p for _, p in layers],
            [shape(i, i) for i in range(len(layers))])
print("/* Generated by TikuTracker/tools/mkreadericon.py.\n"
      " * Authored TikuOS vector artwork; SPDX-License-Identifier: Apache-2.0 */")
print("static const uint8_t tiku_icon_reader[] = {")
for at in range(0, len(blob), 12):
    print("    " + ", ".join(f"0x{b:02x}" for b in blob[at:at+12]) + ",")
print("};")
