"""Emit the Calculator's HVIF icon on the toolkit's 64-unit canvas.

A slate pocket calculator standing upright: a pale display along the top
with a figure in it, and a keypad of ivory keys with the equals key in
orange, readable at 14 px.
SPDX-License-Identifier: Apache-2.0
"""
from mkhvif import icon, path_polygon, shape, style_solid, rect


layers = []


def add(color, points):
    layers.append((style_solid(color), path_polygon(points)))


# The body: a dark outline, the slate face and a lit edge along the top
# and left, the way the toolkit's buttons are lit.
add((28, 31, 38, 255), [(10, 2), (54, 2), (60, 8), (60, 58), (54, 62),
                       (10, 62), (4, 58), (4, 8)])
add((92, 100, 112, 255), [(11, 5), (53, 5), (57, 9), (57, 55), (53, 59),
                         (11, 59), (7, 55), (7, 9)])
add((58, 64, 74, 255), [(13, 8), (55, 8), (57, 10), (57, 55), (53, 59),
                       (13, 59), (10, 56), (10, 11)])
# The display, sunk into the face, with a figure standing at its right.
add((22, 26, 30, 255), rect(11, 9, 53, 23))
add((214, 226, 196, 255), rect(12, 10, 52, 22))
add((40, 48, 40, 255), rect(44, 12, 47, 20))
add((40, 48, 40, 255), rect(36, 12, 39, 20))
add((214, 226, 196, 255), rect(37, 14, 38, 18))
# The keypad: four rows of four keys, the equals key in orange.
for row in range(4):
    for col in range(4):
        x, y = 12 + col * 10, 27 + row * 8
        ink = (232, 140, 48, 255) if (row >= 2 and col == 3) \
            else (238, 234, 222, 255)
        if row == 3 and col == 3:
            continue            # the tall equals key spans two rows
        add((20, 22, 26, 255), rect(x, y, x + 8, y + 6 if col < 3 or
                                   row < 2 else y + 14))
        add(ink, rect(x, y, x + 7, y + 5 if col < 3 or row < 2 else y + 13))

blob = icon([s for s, _ in layers], [p for _, p in layers],
            [shape(i, i) for i in range(len(layers))])
print("/* Generated by tools/icons/mkcalcicon.py.\n"
      " * Authored TikuOS vector artwork; SPDX-License-Identifier: Apache-2.0 */")
print("static const uint8_t tiku_icon_calculator[] = {")
for at in range(0, len(blob), 12):
    print("    " + ", ".join(f"0x{b:02x}" for b in blob[at:at+12]) + ",")
print("};")
