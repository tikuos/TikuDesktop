"""Emit TikuCircuit's HVIF icon on the toolkit's 64-unit canvas.

A green circuit board with gold traces and a chip, and a cream schematic
page over its corner, readable at 14 px.  Run from tools/icons, into
kits/translation/tiku_icons_circuit.inl.
SPDX-License-Identifier: Apache-2.0
"""
from mkhvif import icon, path_polygon, shape, style_solid

layers = []


def add(colour, points):
    layers.append((style_solid(colour), path_polygon(points)))


def rect(colour, x, y, w, h):
    add(colour, [(x, y), (x+w, y), (x+w, y+h), (x, y+h)])


rect((25, 32, 39, 70), 9, 9, 49, 50)
rect((30, 65, 56, 255), 5, 5, 49, 50)
rect((58, 128, 99, 255), 7, 7, 45, 46)
gold = (232, 191, 87, 255)
for y in (17, 25, 33, 41):
    rect(gold, 11, y, 12, 3)
    rect(gold, 38, y, 10, 3)
for x in (24, 31, 38):
    rect(gold, x, 11, 3, 38)
rect((27, 40, 44, 255), 20, 18, 23, 25)
rect((53, 64, 67, 255), 22, 20, 19, 21)
rect((198, 214, 200, 255), 25, 23, 3, 3)
# The cream schematic page sets it apart from a hardware-settings icon.
add((80, 70, 60, 255), [(34, 35), (53, 35), (60, 42), (60, 60), (34, 60)])
add((255, 251, 229, 255), [(36, 37), (52, 37), (58, 43), (58, 58), (36, 58)])
rect((165, 91, 54, 255), 39, 46, 16, 2)
rect((165, 91, 54, 255), 44, 43, 7, 8)
rect((255, 251, 229, 255), 46, 45, 3, 4)

blob = icon([s for s, _ in layers], [p for _, p in layers],
            [shape(i, i) for i in range(len(layers))])
print("/* Generated by tools/icons/mkcircuiticon.py.\n"
      " * Authored artwork; SPDX-License-Identifier: Apache-2.0 */")
print("static const uint8_t tiku_icon_circuit[] = {")
for at in range(0, len(blob), 12):
    print("    " + ", ".join(f"0x{b:02x}" for b in blob[at:at+12]) + ",")
print("};")
