"""Emit toolkit navigation artwork as HVIF C arrays; no raster glyphs.

Run from any directory; uses the same 64-unit canvas as the other icons.
SPDX-License-Identifier: Apache-2.0
"""
import math
from mkhvif import icon, path_polygon, shape, style_solid


def emit(name, layers):
    styles = [style_solid(color) for color, _ in layers]
    paths = [path_polygon(points) for _, points in layers]
    blob = icon(styles, paths, [shape(i, i) for i in range(len(layers))])
    print(f"static const uint8_t tiku_icon_{name}[] = {{")
    for at in range(0, len(blob), 12):
        print("    " + ", ".join(f"0x{b:02x}" for b in blob[at:at+12]) + ",")
    print("};\n")


print("/* Generated by tools/icons/mknavigation.py.\n"
      " * Authored TikuOS vector artwork; SPDX-License-Identifier: Apache-2.0 */")
arrow = [(6, 31), (29, 8), (29, 22), (57, 22), (57, 41),
         (29, 41), (29, 54)]
inner = [(10, 31), (26, 15), (26, 25), (54, 25), (54, 38),
         (26, 38), (26, 47)]
shine = [(10, 31), (26, 15), (26, 25), (54, 25), (54, 29),
         (23, 29), (23, 24), (14, 33)]
for name, flip in [("nav_back", False), ("nav_forward", True)]:
    def mirror(points):
        return [(64-x if flip else x, y) for x, y in points]
    emit(name, [((35, 49, 35, 255), mirror(arrow)),
                ((67, 153, 72, 255), mirror(inner)),
                ((164, 215, 142, 255), mirror(shine))])


def arc(outer, inner):
    angles = [math.radians(25 + i*290/40) for i in range(41)]
    return ([(32 + outer*math.cos(a), 32 + outer*math.sin(a)) for a in angles]
            + [(32 + inner*math.cos(a), 32 + inner*math.sin(a))
               for a in reversed(angles)])


