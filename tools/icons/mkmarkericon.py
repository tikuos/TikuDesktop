"""Emit TikuMarker's HVIF icon on the toolkit's 64-unit canvas.

A page of text with a folded corner and a teal Markdown badge across it,
carrying a white M and a downward arrow, readable at 14 px.  Run from
tools/icons, into kits/translation/tiku_icons_marker.inl.
SPDX-License-Identifier: Apache-2.0
"""
from mkhvif import icon, path_polygon, shape, style_solid

layers = []


def add(color, points):
    layers.append((style_solid(color), path_polygon(points)))


add((30, 39, 50, 50), [(12, 9), (44, 9), (58, 23), (58, 61), (12, 61)])
add((55, 65, 77, 255), [(9, 4), (41, 4), (55, 18), (55, 58), (9, 58)])
add((255, 251, 237, 255), [(11, 6), (40, 6), (53, 19), (53, 56), (11, 56)])
add((171, 181, 187, 255), [(40, 6), (53, 19), (40, 19)])
add((220, 230, 230, 255), [(42, 9), (51, 17), (42, 17)])
for y, right in ((14, 32), (21, 34), (28, 46), (51, 43)):
    add((139, 153, 159, 255), [(16, y), (right, y), (right, y+2), (16, y+2)])
# Teal badge, with a white M and downward arrow, recognizable at menu sizes.
add((26, 74, 83, 255), [(5, 32), (59, 32), (59, 48), (5, 48)])
add((40, 127, 140, 255), [(7, 34), (57, 34), (57, 46), (7, 46)])
add((255, 255, 245, 255), [(12, 44), (12, 36), (16, 36), (21, 40),
                         (26, 36), (30, 36), (30, 44), (26, 44),
                         (26, 40), (21, 44), (16, 40), (16, 44)])
add((255, 255, 245, 255), [(41, 35), (45, 35), (45, 40), (50, 40),
                         (43, 45), (36, 40), (41, 40)])

blob = icon([s for s, _ in layers], [p for _, p in layers],
            [shape(i, i) for i in range(len(layers))])
print("/* Generated by tools/icons/mkmarkericon.py.\n"
      " * Authored TikuOS vector artwork; SPDX-License-Identifier: Apache-2.0 */")
print("static const uint8_t tiku_icon_marker[] = {")
for at in range(0, len(blob), 12):
    print("    " + ", ".join(f"0x{b:02x}" for b in blob[at:at+12]) + ",")
print("};")
