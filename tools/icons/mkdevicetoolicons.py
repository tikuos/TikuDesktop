"""Emit the Device Tools' HVIF icons on the toolkit's 64-unit canvas.

Five utilities, one mark each, all readable at 14 px: a bench with a
green tick on a chart, a console with a scrolling log, a hex sheet with
a byte grid, a monitor with a live trace, and a magnifier over a tree.
SPDX-License-Identifier: Apache-2.0
"""
import sys
from mkhvif import icon, path_polygon, shape, style_solid, rect, circle, ring

DARK = (28, 31, 38, 255)
SLATE = (70, 76, 88, 255)
LIT = (104, 112, 124, 255)
SCREEN = (14, 20, 18, 255)
GREEN = (92, 230, 120, 255)
PAPER = (255, 252, 236, 255)
INK = (150, 150, 140, 255)
ORANGE = (232, 140, 48, 255)
BLUE = (74, 141, 198, 255)


def frame(layers):
    """A slate screen frame with a lit edge and a stand, screen inside."""
    layers.append((DARK, [(8, 6), (56, 6), (60, 10), (60, 50), (56, 54),
                          (8, 54), (4, 50), (4, 10)]))
    layers.append((LIT, [(9, 9), (55, 9), (57, 11), (57, 49), (55, 51),
                         (9, 51), (7, 49), (7, 11)]))
    layers.append((SLATE, [(11, 12), (55, 12), (57, 14), (57, 49), (55, 51),
                           (11, 51), (9, 49), (9, 14)]))
    layers.append((SCREEN, rect(11, 13, 53, 47)))
    layers.append((DARK, rect(24, 54, 40, 60)))
    layers.append((LIT, rect(26, 55, 38, 58)))


def sheet(layers):
    """An ivory sheet with a folded corner."""
    layers.append(((30, 39, 50, 55), rect(14, 60, 50, 62)))
    layers.append(((70, 66, 58, 255), [(10, 4), (40, 4), (52, 16), (52, 60), (10, 60)]))
    layers.append((PAPER, [(12, 6), (39, 6), (50, 17), (50, 58), (12, 58)]))
    layers.append(((70, 66, 58, 255), [(39, 4), (39, 17), (52, 17)]))
    layers.append(((226, 220, 196, 255), [(40, 7), (40, 16), (49, 16)]))


def bench():
    layers = []
    frame(layers)
    # bars of a chart rising, and a tick over them
    for i, h in enumerate((8, 14, 20, 26)):
        layers.append((BLUE, rect(14 + i * 9, 44 - h, 20 + i * 9, 44)))
    layers.append((GREEN, [(30, 30), (36, 36), (50, 18), (53, 22), (36, 42), (27, 34)]))
    return layers


def console():
    layers = []
    frame(layers)
    for i, w in enumerate((22, 14, 28)):
        layers.append(((60, 140, 80, 255),
                       rect(15, 16 + i * 7, 15 + w, 20 + i * 7)))
    # the prompt at the foot, bright: a chevron and a block cursor
    layers.append((GREEN, [(15, 36), (23, 41), (15, 46), (15, 43), (18, 41),
                           (15, 39)]))
    layers.append((GREEN, rect(26, 37, 36, 45)))
    return layers


def hexsheet():
    layers = []
    sheet(layers)
    for row in range(5):
        for col in range(3):
            x, y = 16 + col * 11, 22 + row * 7
            layers.append((ORANGE if (row + col) % 3 == 0 else INK,
                           rect(x, y, x + 8, y + 4)))
    return layers


def monitor():
    layers = []
    frame(layers)
    # a live trace across the screen
    trace = [(13, 34), (20, 34), (24, 20), (28, 44), (32, 26), (36, 34),
             (51, 34)]
    for (x0, y0), (x1, y1) in zip(trace, trace[1:]):
        layers.append((GREEN, [(x0, y0 - 2), (x1, y1 - 2), (x1, y1 + 2), (x0, y0 + 2)]))
    layers.append((ORANGE, circle(46, 18, 3, 12)))
    return layers


def inspector():
    layers = []
    sheet(layers)
    # a tree of nodes
    layers.append((INK, rect(16, 20, 19, 48)))
    for y in (22, 31, 40, 48):
        layers.append((INK, rect(16, y, 26, y + 3)))
        layers.append((BLUE, rect(25, y - 3, 44, y + 5)))
    # a magnifier over it, from the lower right
    layers.append((DARK, [(40, 44), (54, 58), (58, 54), (44, 40)]))
    layers.append((DARK, ring(37, 37, 13, 8, 20)))
    layers.append(((200, 220, 240, 150), circle(37, 37, 8, 20)))
    layers.append((LIT, ring(37, 37, 11, 9, 20)))
    return layers


ICONS = {"bench": bench, "console": console, "hex": hexsheet,
         "monitor": monitor, "inspector": inspector}
name = sys.argv[1]
layers = ICONS[name]()
blob = icon([style_solid(c) for c, _ in layers],
            [path_polygon(p) for _, p in layers],
            [shape(i, i) for i in range(len(layers))])
print("/* Generated by tools/icons/mkdevicetoolicons.py %s.\n"
      " * Authored TikuOS vector artwork; SPDX-License-Identifier: Apache-2.0 */" % name)
print("static const uint8_t tiku_icon_tool_%s[] = {" % name)
for at in range(0, len(blob), 12):
    print("    " + ", ".join(f"0x{b:02x}" for b in blob[at:at+12]) + ",")
print("};")
