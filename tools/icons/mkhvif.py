"""Author simple solid-colour HVIF icons (64x64 canvas)."""
import struct, os, textwrap

def coord(v):
    if float(v).is_integer() and -32 <= v <= 95:
        return bytes([int(v) + 32])
    n = int(round((v + 128.0) * 102.0))
    n = max(0, min(0x7FFF, n))
    return bytes([0x80 | (n >> 8), n & 0xFF])

def style_solid(rgba):
    r, g, b, a = rgba
    return bytes([1, r, g, b, a])

def f24(v):
    """A float as HVIF's 24-bit one: a sign, six bits of exponent biased
    by 32, the seventeen highest bits of the mantissa."""
    if v == 0:
        return bytes(3)
    bits = struct.unpack(">I", struct.pack(">f", float(v)))[0]
    exp = ((bits >> 23) & 0xFF) - 127 + 32
    if exp < 0:
        return bytes(3)
    exp = min(exp, 63)
    v24 = (bits >> 31) << 23 | exp << 17 | (bits >> 6) & 0x1FFFF
    return bytes([v24 >> 16 & 0xFF, v24 >> 8 & 0xFF, v24 & 0xFF])

def style_linear(p0, p1, stops):
    """A linear gradient from icon point p0 to p1, through (offset 0..1,
    rgba) stops: HVIF's -64..64 span laid along the line between them."""
    (x0, y0), (x1, y1) = p0, p1
    a, b = (x1 - x0) / 128.0, (y1 - y0) / 128.0
    out = bytes([2, 0, 0x02, len(stops)])       # gradient, linear, matrix
    for v in (a, b, -b, a, (x0 + x1) / 2.0, (y0 + y1) / 2.0):
        out += f24(v)
    for off, (r, g, bl, al) in stops:
        out += bytes([int(round(off * 255)), r, g, bl, al])
    return out

def path_polygon(points, closed=True):
    flags = 0x08 | (0x02 if closed else 0)   # NO_CURVES | CLOSED
    out = bytes([flags, len(points)])
    for (x, y) in points:
        out += coord(x) + coord(y)
    return out

def shape(style_idx, path_idx):
    return bytes([10, style_idx, 1, path_idx, 0])

def icon(styles, paths, shapes):
    out = b"ncif"
    out += bytes([len(styles)]) + b"".join(styles)
    out += bytes([len(paths)])  + b"".join(paths)
    out += bytes([len(shapes)]) + b"".join(shapes)
    return out

def circle(cx, cy, r, n=24):
    import math
    return [(cx + r * math.cos(2 * math.pi * i / n),
             cy + r * math.sin(2 * math.pi * i / n)) for i in range(n)]

def ring(cx, cy, ro, ri, n=24):
    """Annulus as one closed path: outer CW then inner CCW."""
    o = circle(cx, cy, ro, n)
    i = circle(cx, cy, ri, n)[::-1]
    return o + [o[0]] + i + [i[0]]

def rect(x0, y0, x1, y1):
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]

def write(name, blob):
    with open("/tmp/newicons/%s.hvif" % name, "wb") as f:
        f.write(blob)
    print("%-16s %4d bytes" % (name, len(blob)))

def header(name, description, command, authored="TikuOS vector artwork"):
    """The kits file header of fragment name, prose wrapped at 75 columns."""
    prose = textwrap.fill("%s - %s  Generated by %s." % (name, description,
                                                         command),
                          75, initial_indent=" * ", subsequent_indent=" * ")
    return ("/*\n"
            " * TikuOS kits -- the foundation TikuDesktop and TikuTracker\n"
            " * both stand on.\n"
            " *\n"
            " * Authors: Ambuj Varshney <ambuj@tiku-os.org>\n"
            " *\n"
            "%s\n"
            " *\n"
            " * Authored %s.\n"
            " * SPDX-License-Identifier: Apache-2.0\n"
            " */" % (prose, authored))
