"""Emit TikuSDR's recording icon as a C array: the document Tracker gives a
.sdrlog, a page holding a dark screen with a spectrum's teal peak over a
strip of waterfall, in the colours the application draws them.

Drawn as the rest of the set: a dark edge, a face shaded from the lit top
left.  Run from tools/icons, into kits/translation/tiku_icons_sdr.inl.
SPDX-License-Identifier: Apache-2.0
"""
from mkhvif import rect
from mktoolbaricons import Art, page

SCREEN = (14, 18, 23, 255)
FILL = (21, 60, 54, 255)
TRACE = (87, 211, 176, 255)
NAVY = (27, 42, 107, 255)
TEAL = (31, 122, 140, 255)
GOLD = (227, 195, 77, 255)

# The trace across the screen, a tall peak left of centre and a lesser one
# to the right: what a Bluetooth advertisement beside Wi-Fi looks like.
TRACE_AT = [(18, 30), (21, 29), (24, 30), (27, 22), (29, 14), (31, 22),
            (34, 29), (37, 27), (40, 24), (43, 27), (46, 30)]


def sdr_file(art):
    """A page, a screen on it, the spectrum filled beneath its trace, and
    the waterfall's rows with the peak burning down through them."""
    page(art, 12, 4, 52, 60, [(51, 17, 46), (55, 17, 38)])
    art.solid(SCREEN, rect(16, 10, 48, 47))
    art.solid(FILL, [(18, 33)] + TRACE_AT + [(46, 33)])
    art.solid(TRACE, TRACE_AT + [(x, y + 2) for x, y in reversed(TRACE_AT)])
    art.solid(NAVY, rect(18, 35, 46, 45))
    art.solid(TEAL, rect(25, 35, 33, 45))
    art.solid(TEAL, rect(38, 37, 43, 45))
    art.solid(GOLD, rect(27, 35, 31, 45))


ICONS = []
for name, draw in (("sdr_file", sdr_file),):
    a = Art()
    draw(a)
    ICONS.append((name, a.blob()))

print("/* Generated by tools/icons/mksdricon.py.\n"
      " * Authored TikuOS vector artwork; "
      "SPDX-License-Identifier: Apache-2.0 */")
for name, blob in ICONS:
    print(f"static const uint8_t tiku_icon_{name}[] = {{")
    for at in range(0, len(blob), 12):
        print("    " + ", ".join(f"0x{b:02x}" for b in blob[at:at + 12]) + ",")
    print("};\n")
