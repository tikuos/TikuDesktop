"""Generate Document Kit's pinned Unicode segmentation property ranges."""
import argparse
import hashlib
from pathlib import Path

VERSION = "17.0.0"
GCB = ("Other CR LF Control Extend ZWJ Regional_Indicator Prepend SpacingMark "
       "L V T LV LVT").split()
WB = ("Other CR LF Newline Extend ZWJ Regional_Indicator Format Katakana "
      "Hebrew_Letter ALetter Single_Quote Double_Quote MidNumLet MidLetter "
      "MidNum Numeric ExtendNumLet WSegSpace").split()
INCB = "None Consonant Extend Linker".split()


def records(path):
    """Yield property fields with parsed code point ranges."""
    for line in path.read_text(encoding="utf-8").splitlines():
        fields = [part.strip() for part in line.split("#", 1)[0].split(";")]
        if len(fields) < 2:
            continue
        bounds = fields[0].split("..")
        yield int(bounds[0], 16), int(bounds[-1], 16), fields[1:]


def generate(source, destination):
    """Merge disjoint property assignments into one checked-in range table."""
    values = [0] * 0x110000
    inputs = {
        "GraphemeBreakProperty.txt": (GCB, 0, None),
        "WordBreakProperty.txt": (WB, 4, None),
        "DerivedCoreProperties.txt": (INCB, 9, "InCB"),
        "emoji-data.txt": (None, 11, "Extended_Pictographic"),
    }
    hashes = []
    for name, (names, shift, wanted) in inputs.items():
        path = source / name
        data = path.read_bytes()
        if name != "emoji-data.txt" and VERSION.encode() not in data[:500]:
            raise ValueError(f"{name}: Unicode version mismatch")
        if name == "emoji-data.txt" and b"# Version: 17.0\n" not in data[:500]:
            raise ValueError(f"{name}: Emoji version mismatch")
        hashes.append((name, hashlib.sha256(data).hexdigest()))
        for first, last, props in records(path):
            if wanted and props[0] != wanted:
                continue
            prop = props[-1] if names else None
            value = names.index(prop) if names else 1
            for cp in range(first, last + 1):
                values[cp] |= value << shift
    lines = ["/*", " * Unicode 17.0.0 segmentation property ranges.",
             " * Generated by tools/gen_richtext_unicode.py.",
             " * Copyright Unicode, Inc. See LICENSE.Unicode.",
             " * SPDX-License-Identifier: Unicode-3.0", " */"]
    for name, digest in hashes:
        lines += [f"/* {name}", f" * SHA-256: {digest}", " */"]
    lines += ["static const unicode_range_t unicode_ranges[] = {"]
    first = 0
    for cp in range(1, len(values) + 1):
        if cp < len(values) and values[cp] == values[first]:
            continue
        if values[first]:
            lines.append(f"    {{0x{first:x}, 0x{cp - 1:x}, {values[first]}}},")
        first = cp
    lines += ["};", ""]
    destination.write_text("\n".join(lines), encoding="utf-8")


def main():
    """Read a local pinned UCD directory; network access is not required."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    generate(args.source, args.destination)


if __name__ == "__main__":
    main()
